function add(title, category, definition, procedure, caution, example, prompt, answer, steps, hint, type = 'number', accepted = []) {
  index += 1;
  const id = `i${grade}-${String(index).padStart(3, '0')}`;
  const field = {key: 'result', label: type === 'list' ? 'Rezultati redom' : 'Tvoj odgovor', answer: String(answer), type};
  if (type === 'list') field.ordered = true;
  if (type === 'text') field.caseSensitive = true;
  if (accepted.length) field.accepted = accepted.map(String);
  lessons.push({id, grade, g: grade, subject: 'informatics', title, category,
    description: definition, body: [definition, procedure, caution], example,
    activity: {prompt, fields: [field], steps, hint}});
}

